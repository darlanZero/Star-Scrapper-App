  static String translateLabel(String value) =>
      labels[value.trim()] ?? tags[value.trim()] ?? value.trim();

  static String translateMetadata(String value) {
    var result = value;
    final replacements = <String, String>{...labels, ...tags}.entries.toList()
      ..sort((a, b) => b.key.length.compareTo(a.key.length));
    for (final entry in replacements) {
      result = result.replaceAll(entry.key, entry.value);
    }
    result = result.replaceAllMapped(
      RegExp(r'(\d+)\s*秒前'),
      (match) => '${match.group(1)} seconds ago',
    );
    result = result.replaceAllMapped(
      RegExp(r'(\d+)\s*小時前'),
      (match) => '${match.group(1)} hours ago',
    );
    result = result.replaceAllMapped(
      RegExp(r'(\d+)\s*天前'),
      (match) => '${match.group(1)} days ago',
    );
    result = result.replaceAllMapped(
      RegExp(r'(\d+)個月前'),
      (match) => '${match.group(1)} months ago',
    );
    result = result.replaceAllMapped(
      RegExp(r'(\d+)年前'),
      (match) => '${match.group(1)} years ago',
    );
    result = result.replaceAllMapped(
      RegExp(r'(\d+(?:\.\d+)?)萬次'),
      (match) => '${_compactWan(match.group(1)!)} views',
    );
    result = result.replaceAllMapped(
      RegExp(r'(\d+)次'),
      (match) => '${match.group(1)} views',
    );
    return result;
  }

  static String _compactWan(String raw) {
    final value = (double.tryParse(raw) ?? 0) * 10000;
    if (value >= 1000000) {
      final millions = value / 1000000;
      return '${millions.toStringAsFixed(millions >= 10 ? 1 : 2)}M'
          .replaceFirst(RegExp(r'\.0+$'), '');
    }
    if (value >= 1000) {
      final thousands = value / 1000;
      return '${thousands.toStringAsFixed(thousands >= 10 ? 0 : 1)}K'
          .replaceFirst(RegExp(r'\.0$'), '');
    }
    return value.round().toString();
  }
